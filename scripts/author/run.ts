/**
 * Generates one topic.
 *
 *   npx tsx scripts/author/run.ts <topic-spec> [--count N] [--out file.ts]
 *
 * Every generated program runs under the seatbelt profile — this is the
 * unattended path the sandbox exists for.
 */

import { writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { homedir } from "node:os";
import { parseArgs } from "node:util";

import { ALL } from "../../content/index.js";
import { ClaudeCodeProvider } from "../../src/main/ai/adapters/claude-code.js";
import { authorOne, type Outcome } from "./pipeline.js";
import type { TopicSpec } from "../../content/specs/types.js";
import type { Difficulty, Problem } from "../../content/types.js";

const { values, positionals } = parseArgs({
  allowPositionals: true,
  options: { count: { type: "string" }, out: { type: "string" } },
});

const specName = positionals[0];
if (!specName) {
  console.error("usage: run.ts <spec-name> [--count N] [--out file]");
  process.exit(2);
}
const { SPEC } = (await import(`../../content/specs/${specName}.js`)) as { SPEC: TopicSpec };
const target = Number(values.count ?? 4);

/**
 * The difficulty queue, from the spec's targetCounts, trimmed to `target`.
 *
 * Interleaved rather than grouped so an interrupted run still leaves a usable
 * mix rather than eight easy problems and nothing else.
 */
function difficultyQueue(): Difficulty[] {
  const pools: Difficulty[][] = (["easy", "medium", "hard"] as Difficulty[]).map((d) =>
    Array.from({ length: SPEC.targetCounts[d] ?? 0 }, () => d),
  );
  const out: Difficulty[] = [];
  for (let i = 0; out.length < target; i++) {
    let added = false;
    for (const pool of pools) {
      if (pool.length > i && out.length < target) {
        out.push(pool[i]!);
        added = true;
      }
    }
    if (!added) break;
  }
  while (out.length < target) out.push("medium");
  return out;
}
const queue = difficultyQueue();

const provider = new ClaudeCodeProvider(join(homedir(), ".local/bin/claude"));
const existing = ALL.map((p) => ({ id: p.id, title: p.title, prompt: p.prompt }));
const accepted: Problem[] = [];
const rejected: { title: string; reason: string }[] = [];
const avoid: string[] = [];

const started = Date.now();
console.log(`authoring ${target} problems for "${SPEC.topic}" — sandboxed, gated`);
console.log(`difficulty mix: ${queue.join(", ")}\n`);

for (let i = 0; accepted.length < target && i < target * 2; i++) {
  const t0 = Date.now();
  const want = queue[accepted.length] ?? "medium";
  console.log(`[${accepted.length + 1}/${target}] attempt ${i + 1} — want ${want}`);
  let outcome: Outcome;
  try {
    outcome = await authorOne(
      {
        spec: SPEC,
        existing: [...existing, ...accepted.map((p) => ({ id: p.id, title: p.title, prompt: p.prompt }))],
        provider,
        log: (l) => console.log(l),
        workRoot: join(tmpdir(), "jt-author"),
        runtimeDir: join(process.cwd(), "runtime", "java"),
        sandboxProfile: join(process.cwd(), "runtime", "sandbox.sb"),
      },
      avoid,
      want,
    );
  } catch (e) {
    console.log(`  ERROR ${(e as Error).message.slice(0, 120)}\n`);
    continue;
  }

  const secs = ((Date.now() - t0) / 1000).toFixed(0);
  if (outcome.status === "accepted") {
    accepted.push(outcome.problem);
    avoid.push(outcome.problem.title);
    console.log(`  ACCEPTED in ${secs}s${outcome.repairs > 0 ? ` after ${outcome.repairs} repair(s)` : ""}\n`);
  } else {
    rejected.push({ title: outcome.title, reason: outcome.reason });
    avoid.push(outcome.title);
    console.log(`  rejected in ${secs}s — ${outcome.reason.slice(0, 140)}\n`);
  }
}

const mins = ((Date.now() - started) / 60000).toFixed(1);
console.log(`\n${accepted.length} accepted, ${rejected.length} rejected, ${mins} min`);
for (const r of rejected) console.log(`  rejected: ${r.title} — ${r.reason.slice(0, 100)}`);

if (accepted.length > 0) {
  const out = values.out ?? `content/problems/generated-${SPEC.topic}.ts`;
  const body = `import type { Problem } from "../types.js";

/**
 * Generated by scripts/author/run.ts from content/specs/${specName}.ts,
 * then cleared: static validation, compile-and-run, starter-must-fail and
 * mutant-must-fail. Every one still needs a human to read its prompt.
 */
export const GENERATED: Problem[] = ${JSON.stringify(accepted, null, 2)};
`;
  await writeFile(out, body, "utf8");
  console.log(`\nwrote ${out}`);
}
